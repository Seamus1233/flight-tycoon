"""
Generates the Roblox config modules and the Blender input JSON from
tools/aircraft_data.py, and prints an economy simulation.

    python3 tools/generate.py            # write files + print sim summary
    python3 tools/generate.py --verbose  # also print the full purchase timeline
"""
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from aircraft_data import AIRCRAFT, ERAS, FACILITIES  # noqa: E402

# ---------------------------------------------------------------- economy knobs
BASE_INCOME = 4            # $/s the empty plot earns (the "Scrap Yard")
FIRST_PLANE_COST = 60
COST_GROWTH = 1.47         # cost multiplier per aircraft
PAYBACK_START = 40         # seconds for the first aircraft to pay for itself
PAYBACK_GROWTH = 1.112     # payback time grows per aircraft (slows late game)
FACILITY_COST_FACTOR = 1.6 # facility cost relative to the next aircraft
GATE_COST_FACTOR = 3.0     # era gate cost relative to the next aircraft
REBIRTH_BONUS = 0.5        # +50% income per rebirth


def nice(n):
    """Round to 2 significant figures so prices look clean (12,000 not 12,317)."""
    if n < 100:
        return int(round(n))
    mag = 10 ** (int(math.log10(n)) - 1)
    return int(round(n / mag) * mag)


def build_items():
    free = [a for a in AIRCRAFT if not a["premium"]]
    items = []
    plane_index = 0
    by_era = {}
    for a in free:
        by_era.setdefault(a["era"], []).append(a)
    fac_by_era = {}
    for f in FACILITIES:
        fac_by_era.setdefault(f[0], []).append(f)

    prev_id = None
    for era in sorted(by_era):
        planes = by_era[era]
        facs = [f for f in fac_by_era.get(era, []) if not f[4]]
        gates = [f for f in fac_by_era.get(era, []) if f[4]]
        # spread the non-gate facilities evenly through the era
        slots = {}
        for i, f in enumerate(facs):
            after = max(0, round((i + 1) * len(planes) / (len(facs) + 1)) - 1)
            slots.setdefault(after, []).append(f)
        for pi, a in enumerate(planes):
            cost = nice(FIRST_PLANE_COST * COST_GROWTH ** plane_index)
            payback = PAYBACK_START * PAYBACK_GROWTH ** plane_index
            income = max(1, nice(cost / payback))
            items.append(dict(id=a["id"], kind="aircraft", era=era, name=a["name"], cost=cost,
                              income=income, requires=prev_id, planeIndex=plane_index))
            prev_id = a["id"]
            plane_index += 1
            for f in slots.get(pi, []):
                nxt = FIRST_PLANE_COST * COST_GROWTH ** plane_index
                items.append(dict(id=f[1], kind="facility", era=era, name=f[2],
                                  cost=nice(nxt * FACILITY_COST_FACTOR), bonus=f[3], requires=prev_id,
                                  gate=False))
        for f in gates:
            nxt = FIRST_PLANE_COST * COST_GROWTH ** plane_index
            items.append(dict(id=f[1], kind="facility", era=era, name=f[2],
                              cost=nice(nxt * GATE_COST_FACTOR), bonus=f[3], requires=prev_id, gate=True))
            prev_id = f[1]  # next era's first plane requires the gate
    # final-era non-gate facilities that land after the last plane keep requires=last plane
    return items


def simulate(items, mult=1.0, verbose=False):
    cash, t, income_planes, bonus = 0.0, 0.0, 0.0, 0.0
    timeline = []
    for it in items:
        rate = (BASE_INCOME + income_planes) * (1 + bonus) * mult
        need = max(0.0, it["cost"] - cash)
        dt = need / rate
        t += dt
        cash += dt * rate - it["cost"]
        if it["kind"] == "aircraft":
            income_planes += it["income"]
        else:
            bonus += it.get("bonus", 0)
        timeline.append((t, it["name"], it["cost"], rate))
    if verbose:
        for t_, n, c, r in timeline:
            print(f"  {t_/60:7.1f} min  {n:32s} ${c:>16,}   (${r:,.0f}/s)")
    return t, (BASE_INCOME + income_planes) * (1 + bonus) * mult


def lua_value(v, indent=""):
    if isinstance(v, bool):
        return "true" if v else "false"
    if v is None:
        return "nil"
    if isinstance(v, (int,)):
        return str(v)
    if isinstance(v, float):
        return repr(round(v, 4))
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, (list, tuple)):
        return "{" + ", ".join(lua_value(x, indent) for x in v) + "}"
    if isinstance(v, dict):
        inner = indent + "\t"
        parts = []
        for k, x in v.items():
            if x is None:
                continue
            parts.append(f"{inner}{k} = {lua_value(x, inner)},")
        return "{\n" + "\n".join(parts) + "\n" + indent + "}"
    raise TypeError(type(v))


HEADER = "-- AUTO-GENERATED by tools/generate.py from tools/aircraft_data.py. Do not edit by hand.\n"


def main():
    verbose = "--verbose" in sys.argv
    items = build_items()

    # ---- Aircraft.lua
    aircraft_lua = []
    for a in AIRCRAFT:
        d = {k: a[k] for k in ("id", "name", "nation", "era", "role", "L", "S", "speed", "nose", "props",
                               "jets", "pods", "wing", "sweep", "taper", "dihedral", "tail", "canard",
                               "special", "premium", "blurb")}
        d["color"] = [round(c, 3) for c in a["color"]]
        aircraft_lua.append(d)
    out = [HEADER, "local Aircraft = {}\n", "Aircraft.List = {"]
    for d in aircraft_lua:
        out.append("\t" + lua_value(d, "\t") + ",")
    out.append("}\n")
    out.append("Aircraft.ById = {}\nfor i, a in ipairs(Aircraft.List) do\n\ta.order = i\n\tAircraft.ById[a.id] = a\nend\n")
    out.append("Aircraft.Eras = " + lua_value([{"id": e["id"], "name": e["name"], "years": e["years"],
                                                 "color": list(e["color"])} for e in ERAS]) + "\n")
    out.append("return Aircraft\n")
    with open(os.path.join(ROOT, "src/shared/Config/Aircraft.lua"), "w") as f:
        f.write("\n".join(out))

    # ---- Items.lua
    out = [HEADER, "local Items = {}\n",
           f"Items.BaseIncome = {BASE_INCOME}",
           f"Items.RebirthBonus = {REBIRTH_BONUS}\n",
           "Items.List = {"]
    for it in items:
        out.append("\t" + lua_value(it, "\t") + ",")
    out.append("}\n")
    out.append("Items.ById = {}\nfor i, it in ipairs(Items.List) do\n\tit.order = i\n\tItems.ById[it.id] = it\nend\n")
    out.append("-- The item whose purchase makes the player eligible to rebirth.\n"
               f"Items.FinalItemId = {json.dumps([i for i in items if i['kind']=='aircraft'][-1]['id'])}\n")
    out.append("return Items\n")
    with open(os.path.join(ROOT, "src/shared/Config/Items.lua"), "w") as f:
        f.write("\n".join(out))

    # ---- JSON for Blender
    with open(os.path.join(ROOT, "data/aircraft.json"), "w") as f:
        json.dump({"aircraft": AIRCRAFT, "eras": ERAS}, f, indent=1)

    # ---- economy report
    planes = [i for i in items if i["kind"] == "aircraft"]
    print(f"{len(items)} purchasable items: {len(planes)} aircraft + {len(items)-len(planes)} facilities "
          f"(+{sum(1 for a in AIRCRAFT if a['premium'])} premium aircraft)")
    print(f"Final aircraft {planes[-1]['name']}: ${planes[-1]['cost']:,}")
    for label, m in [("Free player", 1.0), ("2x Cash pass", 2.0), ("2x + VIP + Overdrive", 2 * 1.5 * 1.25),
                     ("Free, after 1 rebirth", 1.5), ("Free, after 5 rebirths", 3.5)]:
        t, final_rate = simulate(items, m, verbose=verbose and m == 1.0)
        print(f"  {label:26s} first completion in {t/3600:5.2f} h   (end income ${final_rate:,.0f}/s)")


if __name__ == "__main__":
    main()
